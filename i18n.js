  function detectLocale() {
    // SEO: la URL por idioma manda (/es/, /de/, …) para que el contenido coincida
    // con el <title>/hreflang pre-renderizado de esa página.
    const seg = (location.pathname.split('/').filter(Boolean)[0] || '').toLowerCase();
    if (seg && STRINGS[seg] && SUPPORTED.some((s) => s.code === seg)) return seg;
    const stored = (() => {
      try { return localStorage.getItem('verdesk.lang'); } catch (_) { return null; }
    })();
    if (stored && STRINGS[stored]) return stored;
    const nav = (navigator.language || 'en').toLowerCase();
    for (const { code } of SUPPORTED) {
      if (nav === code || nav.startsWith(code + '-')) return STRINGS[code] ? code : 'en';
    }
    return 'en';
  }

  function apply(locale) {
    const dict = STRINGS[locale] || STRINGS.en;
    document.documentElement.lang = locale;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] != null) el.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] != null) el.innerHTML = dict[key];
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
      const key = el.getAttribute('data-i18n-alt');
      if (dict[key] != null) el.setAttribute('alt', dict[key]);
    });
    // Sync the selector if present
    const sel = document.getElementById('lang-select');
    if (sel && sel.value !== locale) sel.value = locale;
  }

  function buildSelector(current) {
    const sel = document.getElementById('lang-select');
    if (!sel) return;
    sel.innerHTML = '';
    for (const { code, name } of SUPPORTED) {
      const opt = document.createElement('option');
      opt.value = code;
      opt.textContent = name;
      if (code === current) opt.selected = true;
      sel.appendChild(opt);
    }
    sel.addEventListener('change', () => {
      const v = sel.value;
      try { localStorage.setItem('verdesk.lang', v); } catch (_) { /* noop */ }
      // SEO: cambiar idioma = navegar a su URL propia (/es/, /de/, …; en = raíz).
      const target = (v === 'en') ? '/' : '/' + v + '/';
      const cur = location.pathname.endsWith('/') ? location.pathname : location.pathname + '/';
      if (cur !== target) location.href = target; else apply(v);
    });
  }

  // ct-2026-10-14-1013: botón Copiar del comando de instalación (el texto del botón sale de la tabla del idioma).
  function wireInstallCopy(locale) {
    const btn = document.getElementById('install-copy');
    const cmd = document.getElementById('install-cmd');
    if (!btn || !cmd) return;
    const dict = STRINGS[locale] || STRINGS.en;
    const label = (k) => dict[k] != null ? dict[k] : STRINGS.en[k];
    let timer = null;
    const flash = () => {
      btn.textContent = label('install.copied');
      clearTimeout(timer);
      timer = setTimeout(() => { btn.textContent = label('install.copy'); }, 1800);
    };
    const fallback = (text) => {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.setAttribute('readonly', '');
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      let ok = false;
      try { ok = document.execCommand('copy'); } catch (_) { ok = false; }
      document.body.removeChild(ta);
      return ok;
    };
    btn.addEventListener('click', () => {
      const text = cmd.textContent.trim();
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(flash, () => { if (fallback(text)) flash(); });
      } else if (fallback(text)) {
        flash();
      }
    });
  }

  function boot() {
    const locale = detectLocale();
    buildSelector(locale);
    apply(locale);
    wireInstallCopy(locale);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
